"""Зафиксировать текущую проверенную Windows-среду сборки с SHA-256 wheel-файлов."""

from __future__ import annotations

import hashlib
import importlib.metadata
import subprocess
import sys
import tempfile
from pathlib import Path

from packaging.utils import canonicalize_name, parse_wheel_filename

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "requirements-build.lock"
EXCLUDED = {"word-addin-copilot-public"}  # локальный проект устанавливается отдельно с --no-deps


def installed() -> dict[str, tuple[str, str]]:
    result: dict[str, tuple[str, str]] = {}
    for dist in importlib.metadata.distributions():
        display = dist.metadata["Name"]
        name = canonicalize_name(display)
        if name not in EXCLUDED:
            result[name] = (display, dist.version)
    return dict(sorted(result.items()))


def main() -> None:
    packages = installed()
    with tempfile.TemporaryDirectory(prefix="wac-lock-") as temporary:
        wheelhouse = Path(temporary)
        pins = [f"{display}=={version}" for display, version in packages.values()]
        subprocess.run(
            [
                sys.executable,
                "-m",
                "pip",
                "download",
                "--disable-pip-version-check",
                "--no-deps",
                "--only-binary=:all:",
                "--dest",
                str(wheelhouse),
                *pins,
            ],
            check=True,
        )

        wheels: dict[tuple[str, str], Path] = {}
        for wheel in wheelhouse.glob("*.whl"):
            name, version, _, _ = parse_wheel_filename(wheel.name)
            wheels[(canonicalize_name(name), str(version))] = wheel

        lines = [
            "# Generated by tools/lock_build_environment.py from the verified Windows build venv.",
            "# Install dependencies first, then the local project with: pip install --no-deps -e .",
            "--only-binary=:all:",
            "",
        ]
        missing: list[str] = []
        for name, (display, version) in packages.items():
            wheel = wheels.get((name, version))
            if wheel is None:
                missing.append(f"{display}=={version}")
                continue
            digest = hashlib.sha256(wheel.read_bytes()).hexdigest()
            lines.extend([f"{display}=={version} \\", f"    --hash=sha256:{digest}"])
        if missing:
            raise RuntimeError(f"Не найдены wheel-файлы: {', '.join(missing)}")
        OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"Зафиксировано {len(packages)} пакетов: {OUTPUT}")


if __name__ == "__main__":
    main()
